// Writes THIRD_PARTY_NOTICES.md: every library bundled into the app (the frontend packages
// and everything they depend on), with its license and copyright lines; and public/licenses.txt
// with the full texts, shipped inside the app.
//   node tools/licenses.mjs
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = new URL("..", import.meta.url).pathname;
const pkg = JSON.parse(readFileSync(join(root, "package.json"), "utf8"));

// What Vite bundles into dist/ (build tools, types and the Electron/Capacitor shells left out).
const TOOLS = /^(@capacitor\/cli|@types\/|@vitejs\/|electron|electron-builder|typescript|vite|vitest)$/;
const start = [...Object.keys(pkg.dependencies ?? {}), ...Object.keys(pkg.devDependencies ?? {})].filter(n => !TOOLS.test(n));
const seen = new Map();

function find(name, from) {
  for (let dir = from; ; dir = join(dir, "..")) {
    const p = join(dir, "node_modules", name);
    if (existsSync(join(p, "package.json"))) return p;
    if (dir === root || dir === "/") return null;
  }
}

function visit(name, from) {
  const dir = find(name, from);
  if (!dir) return;
  const p = JSON.parse(readFileSync(join(dir, "package.json"), "utf8"));
  const key = `${p.name}@${p.version}`;
  if (seen.has(key)) return;
  const lic = readdirSync(dir).find(f => /^(licen[cs]e|copying)/i.test(f));
  const text = lic ? readFileSync(join(dir, lic), "utf8") : "";
  const copyright = [...new Set(text.split("\n").filter(l => /copyright\s*(\(c\)|©|\d{4})/i.test(l)).map(l => l.trim()))].slice(0, 3);
  seen.set(key, { text, name: p.name, version: p.version, license: typeof p.license === "string" ? p.license : p.license?.type ?? "see package", url: p.homepage ?? p.repository?.url ?? "", copyright });
  for (const d of Object.keys(p.dependencies ?? {})) visit(d, dir);
}

for (const n of start) visit(n, root);

const rows = [...seen.values()].sort((a, b) => a.name.localeCompare(b.name));
const out = [
  "# Third-party notices",
  "",
  "Studium is MIT licensed (see LICENSE). The app bundles the open-source libraries below; each",
  "keeps its own license. Generated by `node tools/licenses.mjs` from the installed packages.",
  "",
  "Ideas from Obsidian plugins (no code taken from them): Advanced Tables and Recent Files",
  "(Tony Grosinger), Remember cursor position (Dmitry Savosh). The table editing itself is done",
  "by md-advanced-tables (MIT), the library Advanced Tables is built on. Appearance settings",
  "follow Obsidian's Appearance page and the Style Settings plugin (mgmeyers, GPL-3.0) as ideas",
  "only. Drawings use the Excalidraw editor (MIT, below) and the file format of the Obsidian",
  "Excalidraw plugin (zsviczian, AGPL-3.0); no plugin code is used.",
  "",
  "Color schemes follow the palettes of Catppuccin (MIT), Nord (MIT), Gruvbox (MIT) and Atom One",
  "(MIT). Excalidraw's fonts ship inside @excalidraw/excalidraw and are copied into the app:",
  "Excalifont, Virgil, Nunito, Lilita One, Cascadia Code, Liberation Sans and Assistant (SIL Open",
  "Font License 1.1) and Comic Shanns (MIT).",
  "",
  "| Library | Version | License | Copyright |",
  "| --- | --- | --- | --- |",
  ...rows.map(r => `| ${r.url ? `[${r.name}](${r.url.replace(/^git\+/, "").replace(/\.git$/, "")})` : r.name} | ${r.version} | ${r.license} | ${r.copyright.join("<br>").replace(/\|/g, "\\|") || "—"} |`),
  "",
];
writeFileSync(join(root, "THIRD_PARTY_NOTICES.md"), out.join("\n"));
// The full license texts go into the app itself (Vite copies public/ into every build).
const byText = new Map();
for (const r of rows) {
  const k = r.text.trim() || `${r.license} (no license file in the package)`;
  byText.set(k, [...(byText.get(k) ?? []), `${r.name}@${r.version}`]);
}
mkdirSync(join(root, "public"), { recursive: true });
writeFileSync(
  join(root, "public", "licenses.txt"),
  `Open-source libraries in Studium and their licenses.\n\n${[...byText].map(([text, names]) => `${"=".repeat(72)}\n${names.join(", ")}\n${"-".repeat(72)}\n${text}\n`).join("\n")}`,
);
console.log(`THIRD_PARTY_NOTICES.md: ${rows.length} libraries; public/licenses.txt: ${byText.size} texts`);
const licenses = {};
for (const r of rows) licenses[r.license] = (licenses[r.license] ?? 0) + 1;
console.log(licenses);
